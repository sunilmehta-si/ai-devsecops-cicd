"""Every Python package a workflow installs comes from a hash-locked file, so CI runs the code that was reviewed."""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORKFLOWS = sorted((ROOT / ".github/workflows").glob("*.yml"))
LOCKS = ROOT / ".github/requirements"


def pins(text: str) -> dict[str, str]:
    return {m.group(1).lower(): m.group(2) for m in re.finditer(r"^([A-Za-z0-9._-]+)==(\S+)", text, re.M)}


class WorkflowPinTests(unittest.TestCase):
    def test_every_pip_install_in_a_workflow_uses_a_hash_locked_file(self):
        installs = []
        for wf in WORKFLOWS:
            for line in wf.read_text().splitlines():
                if re.search(r"\bpip3? install\b", line):
                    installs.append((wf.name, line.strip()))
        self.assertTrue(installs)
        for name, line in installs:
            with self.subTest(workflow=name, line=line):
                m = re.search(r"pip3? install --require-hashes -r (\.github/requirements/[\w-]+\.txt)$", line)
                self.assertIsNotNone(m, "install from a lock in .github/requirements with --require-hashes")
                self.assertTrue((ROOT / m.group(1)).is_file())

    def test_each_lock_pins_every_package_with_hashes_and_matches_its_input(self):
        for lock in sorted(LOCKS.glob("*.txt")):
            with self.subTest(lock=lock.name):
                text = lock.read_text()
                self.assertIn("--uploaded-prior-to P14D", text)          # compiled from releases at least 14 days old
                blocks = re.split(r"^(?=[A-Za-z0-9._-]+==)", text, flags=re.M)[1:]
                self.assertTrue(blocks)
                for block in blocks:
                    self.assertRegex(block, r"--hash=sha256:[0-9a-f]{64}", block.split()[0])
                wanted = pins(lock.with_suffix(".in").read_text())
                self.assertTrue(wanted)
                for name, version in wanted.items():
                    self.assertEqual(pins(text).get(name), version, name)

    def test_dependabot_updates_the_locks_after_the_same_14_days(self):
        config = (ROOT / ".github/dependabot.yml").read_text()
        block = config.split("package-ecosystem: pip", 1)[1].split("- package-ecosystem:", 1)[0]
        self.assertIn("directory: /.github/requirements", block)
        self.assertRegex(block, r"cooldown:\s*\n\s*default-days: 14")

    def test_semgrep_runs_on_the_python_its_lock_was_compiled_for(self):
        text = (ROOT / ".github/workflows/security.yml").read_text()
        job = text.split("  sast:", 1)[1].split("\n  filesystem-and-config:", 1)[0]
        self.assertIn('python-version: "3.14"', job)
        self.assertIn("autogenerated by pip-compile with Python 3.14", (LOCKS / "semgrep.txt").read_text())


if __name__ == "__main__":
    unittest.main()
